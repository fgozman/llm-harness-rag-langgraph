"""Records provenance (URL, publication date, license) of every corpus file; renders SOURCES.md."""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from pathlib import Path

# Written next to SOURCES.md so `rag ingest data/test_corpus` indexes documents, not the provenance table.
RAGIGNORE = "# Corpus metadata, not content (see rag.ingestion.discovery)\nSOURCES.md\n"


@dataclass(frozen=True, slots=True)
class SourceRecord:
    path: str  # relative to the corpus output dir
    source: str
    title: str
    url: str
    published: str
    license: str
    license_url: str | None = None
    pre_cutoff: bool = False
    fiction: bool = False
    notes: str = ""


class Registry:
    def __init__(self, path: Path) -> None:
        self._path = path
        self._records: dict[str, SourceRecord] = {}
        if path.exists():
            for raw in json.loads(path.read_text()):
                record = SourceRecord(**raw)
                self._records[record.path] = record

    @property
    def records(self) -> list[SourceRecord]:
        return sorted(self._records.values(), key=lambda r: (r.source, r.path))

    def has(self, path: str) -> bool:
        return path in self._records

    def upsert(self, record: SourceRecord) -> None:
        self._records[record.path] = record

    def prune_missing(self, out_dir: Path) -> list[str]:
        """Forget records whose files were deleted (e.g. replaced by hand), so SOURCES.md matches the disk."""
        gone = [p for p in self._records if not (out_dir / p).exists()]
        for p in gone:
            del self._records[p]
        return sorted(gone)

    def save(self) -> None:
        self._path.parent.mkdir(parents=True, exist_ok=True)
        self._path.write_text(json.dumps([asdict(r) for r in self.records], indent=2) + "\n")

    def render_markdown(self) -> str:
        lines = [
            "# Test corpus sources",
            "",
            "Generated by `scripts/build_test_corpus.py`. Do not commit the downloaded documents.",
            "",
            "| file | source | title | published | URL | license | flags / notes |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in self.records:
            flags = [
                f for f, on in (("pre_cutoff: true", r.pre_cutoff), ("FICTION (canary)", r.fiction)) if on
            ]
            if r.notes:
                flags.append(r.notes)
            license_cell = f"[{r.license}]({r.license_url})" if r.license_url else r.license
            cells = [r.path, r.source, r.title, r.published, r.url, license_cell, "; ".join(flags)]
            lines.append("| " + " | ".join(c.replace("|", "\\|").replace("\n", " ") for c in cells) + " |")
        return "\n".join(lines) + "\n"
